# -*- coding: utf-8 -*-
"""Controlled access to job artifacts.

Artifacts are only reachable through the manifest written for a job: absolute
paths, ``..`` escapes and paths outside the job directory are rejected, and
tabular files are always returned as bounded pages instead of full dumps.
"""

import csv
import json
import os
from typing import Any, Dict, List, Optional, Tuple

from .constants import (
    DEFAULT_ARTIFACT_LIMIT,
    MAX_ARTIFACT_BYTES,
    MAX_ARTIFACT_LIMIT,
)
from .errors import ErrorCode, MethArCTError
from .paths import is_within, normalize, relative_posix, sha256_file

MANIFEST_FILENAME = "manifest.json"

_MEDIA_TYPES = {
    ".csv": "text/csv",
    ".tsv": "text/tab-separated-values",
    ".json": "application/json",
    ".txt": "text/plain",
    ".log": "text/plain",
    ".xlsx": "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
    ".xls": "application/vnd.ms-excel",
    ".fa": "text/x-fasta",
    ".faa": "text/x-fasta",
    ".fasta": "text/x-fasta",
    ".fna": "text/x-fasta",
}

#: Media types that may be rendered as text to an agent.
TEXT_MEDIA_TYPES = frozenset(
    [
        "text/csv",
        "text/tab-separated-values",
        "application/json",
        "text/plain",
        "text/x-fasta",
    ]
)

_TABULAR_MEDIA_TYPES = frozenset(["text/csv", "text/tab-separated-values"])

#: Filename suffix -> module that produced the file.
_MODULE_BY_SUFFIX = (
    ("_metabolic_summary.csv", "pathway"),
    ("_diamond.tsv", "pathway"),
    ("_cultivation.csv", "cultivation"),
    ("_amino_acid_biosynthesis.csv", "cultivation"),
    ("_huainanzi_summary.tsv", "temperature"),
    ("_susha_summary.tsv", "salinity"),
    ("_susha_result.xlsx", "salinity"),
    ("_ph_summary.tsv", "ph"),
    ("_ph_details.json", "ph"),
    ("_antibiotic_selection.tsv", "antibiotic"),
    ("_checkm2_summary.csv", "genome_quality"),
)


def infer_module_from_filename(filename: str) -> Optional[str]:
    """Infer which module produced *filename*, or ``None`` when unknown."""
    lowered = os.path.basename(filename).lower()
    for suffix, module in _MODULE_BY_SUFFIX:
        if lowered.endswith(suffix):
            return module
    return None


def media_type_for(path: str) -> str:
    """Return the media type for a file extension."""
    extension = os.path.splitext(path)[1].lower()
    return _MEDIA_TYPES.get(extension, "application/octet-stream")


def describe_artifact(path: str) -> str:
    """Human readable one-line description used in the manifest."""
    module = infer_module_from_filename(path)
    if module:
        return "{0} output file generated by the {1} module.".format(
            os.path.basename(path), module
        )
    return "Output file generated by MethArCT."


def _count_rows(path: str, media_type: str) -> Optional[int]:
    """Count data rows for tabular artifacts (streaming)."""
    if media_type == "application/json":
        try:
            with open(path, "r", encoding="utf-8") as stream:
                payload = json.load(stream)
        except (IOError, OSError, ValueError):
            return None
        if isinstance(payload, list):
            return len(payload)
        return None
    if media_type not in _TABULAR_MEDIA_TYPES:
        return None
    delimiter = "\t" if media_type == "text/tab-separated-values" else ","
    try:
        with open(path, "r", encoding="utf-8-sig", errors="replace", newline="") as stream:
            reader = csv.reader(stream, delimiter=delimiter)
            rows = sum(1 for _ in reader)
    except (IOError, OSError, csv.Error):
        return None
    return max(rows - 1, 0)


class ArtifactRegistry(object):
    """Manages the artifact manifest for a single job directory."""

    def __init__(
        self,
        job_dir: str,
        artifact_dir: Optional[str] = None,
        redactions: Optional[List[Tuple[str, str]]] = None,
    ):
        self.job_dir = normalize(job_dir)
        self.artifact_dir = normalize(artifact_dir or (self.job_dir / "artifacts"))
        # Longest first so a nested path is redacted before its parent.
        self.redactions = sorted(
            [(str(source), replacement) for source, replacement in (redactions or []) if source],
            key=lambda item: len(item[0]),
            reverse=True,
        )
        self._entries: List[Dict[str, Any]] = []
        self._by_path: Dict[str, Dict[str, Any]] = {}

    def _sanitize(self, text: str) -> str:
        """Remove host absolute paths from agent-facing artifact content.

        The file on disk is never modified; only the response is redacted. This
        keeps the legacy output byte-identical while preventing an agent from
        learning arbitrary absolute paths.
        """
        if not text or not self.redactions:
            return text
        for source, replacement in self.redactions:
            if source in text:
                text = text.replace(source, replacement)
            posix = source.replace("\\", "/")
            if posix != source and posix in text:
                text = text.replace(posix, replacement)
        return text

    # -- creation ----------------------------------------------------------
    def register_file(self, path: str) -> Optional[Dict[str, Any]]:
        """Register one file that lives inside the job directory."""
        absolute = normalize(path)
        if not is_within(absolute, self.job_dir):
            raise MethArCTError(
                ErrorCode.ARTIFACT_ACCESS_DENIED,
                "Refusing to register a file outside the job directory.",
                details={"path": str(absolute)},
            )
        if not absolute.is_file():
            return None

        key = str(absolute)
        existing = self._by_path.get(key)
        if existing is not None:
            return existing

        relative = relative_posix(absolute, self.job_dir)
        media_type = media_type_for(str(absolute))
        entry = {
            "artifact_id": "a{0:03d}".format(len(self._entries) + 1),
            "path": relative,
            "media_type": media_type,
            "size_bytes": absolute.stat().st_size,
            "sha256": sha256_file(absolute),
            "row_count": _count_rows(str(absolute), media_type),
            "description": describe_artifact(str(absolute)),
            "module": infer_module_from_filename(str(absolute)),
            "filename": absolute.name,
        }
        self._entries.append(entry)
        self._by_path[key] = entry
        return entry

    def scan(self, extra_paths: Optional[List[str]] = None) -> List[Dict[str, Any]]:
        """Register every regular file under the artifact directory."""
        if self.artifact_dir.is_dir():
            for root, _dirs, files in os.walk(str(self.artifact_dir)):
                for name in sorted(files):
                    if name.startswith(".") or name == MANIFEST_FILENAME:
                        continue
                    self.register_file(os.path.join(root, name))
        for path in extra_paths or []:
            self.register_file(path)
        return self._entries

    def write_manifest(self) -> str:
        """Persist ``manifest.json`` next to the artifacts."""
        from .paths import atomic_write_json

        target = self.job_dir / MANIFEST_FILENAME
        atomic_write_json(
            target,
            {
                "artifacts": self._entries,
                "artifact_root": "artifacts",
                "count": len(self._entries),
            },
        )
        return str(target)

    # -- access ------------------------------------------------------------
    @property
    def entries(self) -> List[Dict[str, Any]]:
        return list(self._entries)

    def find_by_path(self, path: str) -> Optional[Dict[str, Any]]:
        """Return the manifest entry whose file matches *path*."""
        try:
            absolute = normalize(path)
        except MethArCTError:  # pragma: no cover - defensive
            return None
        return self._by_path.get(str(absolute))

    def load_manifest(self) -> List[Dict[str, Any]]:
        """Load the manifest from disk (used by read-only API consumers)."""
        manifest_path = self.job_dir / MANIFEST_FILENAME
        try:
            with open(str(manifest_path), "r", encoding="utf-8") as stream:
                payload = json.load(stream)
        except (IOError, OSError, ValueError):
            raise MethArCTError(
                ErrorCode.ARTIFACT_NOT_FOUND,
                "No artifact manifest exists for this job.",
                details={"job_dir": str(self.job_dir)},
            )
        entries = payload.get("artifacts") or []
        self._entries = entries
        self._by_path = {}
        for entry in entries:
            candidate = self.job_dir / entry["path"]
            self._by_path[str(normalize(candidate))] = entry
        return entries

    def resolve(self, artifact_id: str) -> Tuple[Dict[str, Any], str]:
        """Resolve *artifact_id* to its manifest entry and absolute path."""
        if not self._entries:
            self.load_manifest()
        for entry in self._entries:
            if entry["artifact_id"] == artifact_id:
                candidate = normalize(self.job_dir / entry["path"])
                if not is_within(candidate, self.job_dir):
                    raise MethArCTError(
                        ErrorCode.ARTIFACT_ACCESS_DENIED,
                        "Artifact path escapes the job directory.",
                        details={"artifact_id": artifact_id},
                    )
                if not candidate.is_file():
                    raise MethArCTError(
                        ErrorCode.ARTIFACT_NOT_FOUND,
                        "Artifact is listed in the manifest but the file is missing.",
                        details={"artifact_id": artifact_id, "path": entry["path"]},
                    )
                return entry, str(candidate)
        raise MethArCTError(
            ErrorCode.ARTIFACT_NOT_FOUND,
            "Unknown artifact id.",
            details={
                "artifact_id": artifact_id,
                "available": [entry["artifact_id"] for entry in self._entries],
            },
        )

    def read(
        self,
        artifact_id: str,
        offset: int = 0,
        limit: int = DEFAULT_ARTIFACT_LIMIT,
        filter_column: Optional[str] = None,
        filter_value: Optional[str] = None,
        contains: bool = False,
    ) -> Dict[str, Any]:
        """Read one bounded page of an artifact."""
        entry, path = self.resolve(artifact_id)
        media_type = entry.get("media_type") or media_type_for(path)

        offset = max(int(offset or 0), 0)
        limit = int(limit or DEFAULT_ARTIFACT_LIMIT)
        if limit < 1:
            limit = DEFAULT_ARTIFACT_LIMIT
        limit = min(limit, MAX_ARTIFACT_LIMIT)

        if media_type not in TEXT_MEDIA_TYPES:
            raise MethArCTError(
                ErrorCode.ARTIFACT_ACCESS_DENIED,
                "Artifact media type cannot be read as text by an agent.",
                details={"artifact_id": artifact_id, "media_type": media_type},
            )

        if media_type in _TABULAR_MEDIA_TYPES:
            return self._read_tabular(
                entry, path, offset, limit, filter_column, filter_value, contains
            )
        return self._read_textual(entry, path, offset, limit)

    def _read_tabular(
        self,
        entry: Dict[str, Any],
        path: str,
        offset: int,
        limit: int,
        filter_column: Optional[str],
        filter_value: Optional[str],
        contains: bool,
    ) -> Dict[str, Any]:
        delimiter = "\t" if entry.get("media_type") == "text/tab-separated-values" else ","
        columns: List[str] = []
        page_rows: List[Dict[str, Any]] = []
        total_rows = 0
        matched_rows = 0
        bytes_used = 0

        with open(path, "r", encoding="utf-8-sig", errors="replace", newline="") as stream:
            reader = csv.reader(stream, delimiter=delimiter)
            try:
                columns = next(reader)
            except StopIteration:
                columns = []
            if filter_column and filter_column not in columns:
                raise MethArCTError(
                    ErrorCode.INVALID_ARGUMENT,
                    "Filter column does not exist in the artifact.",
                    details={"artifact_id": entry["artifact_id"], "columns": columns},
                )
            index = columns.index(filter_column) if filter_column else None

            for row in reader:
                total_rows += 1
                if index is not None:
                    cell = row[index] if index < len(row) else ""
                    if contains:
                        if filter_value not in cell:
                            continue
                    elif cell != filter_value:
                        continue
                matched_rows += 1
                if matched_rows <= offset:
                    continue
                if len(page_rows) >= limit:
                    continue
                record = {name: (row[i] if i < len(row) else None) for i, name in enumerate(columns)}
                if self.redactions:
                    record = {
                        key: (self._sanitize(value) if isinstance(value, str) else value)
                        for key, value in record.items()
                    }
                page_rows.append(record)
                bytes_used += sum(len(str(value or "")) for value in record.values())
                if bytes_used > MAX_ARTIFACT_BYTES:  # pragma: no cover - safety valve
                    break

        next_offset = offset + len(page_rows)
        if next_offset >= matched_rows:
            next_offset = None
        return {
            "artifact_id": entry["artifact_id"],
            "media_type": entry.get("media_type"),
            "columns": columns,
            "rows": page_rows,
            "total_rows": total_rows,
            "matched_rows": matched_rows,
            "returned_rows": len(page_rows),
            "offset": offset,
            "next_offset": next_offset,
            "filter": {"column": filter_column, "value": filter_value, "contains": contains}
            if filter_column
            else None,
            "truncated": next_offset is not None,
        }

    def _read_textual(
        self, entry: Dict[str, Any], path: str, offset: int, limit: int
    ) -> Dict[str, Any]:
        with open(path, "r", encoding="utf-8-sig", errors="replace", newline="") as stream:
            lines = stream.readlines()

        total_lines = len(lines)
        page = lines[offset : offset + limit]
        text = "".join(page)
        if self.redactions:
            text = self._sanitize(text)
        truncated = False
        if len(text.encode("utf-8")) > MAX_ARTIFACT_BYTES:
            text = text[:MAX_ARTIFACT_BYTES]
            truncated = True
        next_offset = offset + len(page)
        if next_offset >= total_lines:
            next_offset = None
        return {
            "artifact_id": entry["artifact_id"],
            "media_type": entry.get("media_type"),
            "content": text,
            "total_lines": total_lines,
            "returned_lines": len(page),
            "offset": offset,
            "next_offset": next_offset,
            "truncated": truncated or next_offset is not None,
        }
